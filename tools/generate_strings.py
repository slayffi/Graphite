#!/usr/bin/env python3
"""Writes composeResources/values{,-ru}/strings.xml for ui:app from tools/strings_app.py."""
import importlib.util
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("strings_app", ROOT / "tools/strings_app.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)


def write(lang_index: int, folder: str) -> None:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/generate_strings.py; edit tools/strings_app.py -->", "<resources>"]
    for key in sorted(mod.S):
        lines.append(f'    <string name="{key}">{escape(mod.S[key][lang_index])}</string>')
    for key in sorted(mod.P):
        lines.append(f'    <plurals name="{key}">')
        for q, text in mod.P[key][lang_index].items():
            lines.append(f'        <item quantity="{q}">{escape(text)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    out = ROOT / "ui/app/src/commonMain/composeResources" / folder / "strings.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


write(0, "values")
write(1, "values-ru")
print(f"{len(mod.S)} strings, {len(mod.P)} plurals")
