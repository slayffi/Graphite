#!/usr/bin/env python3
"""Generates GraphiteIcons.kt from lucide-static SVG files (ISC license).

Usage: python3 tools/generate_icons.py <lucide-static>/icons <output.kt>

Every SVG element (path, circle, ellipse, rect, line, polyline, polygon) is converted to SVG path data
and emitted as a Compose ImageVector with a 1.5 stroke, round caps and joins, as the design requires.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ICONS = [
    "activity", "arrow-down", "arrow-left", "arrow-up", "arrow-up-down", "battery", "battery-low", "bell",
    "calendar", "calendar-clock", "captions", "chart-column", "chart-line", "check", "check-check",
    "chevron-down", "chevron-left", "chevron-right", "chevron-up", "circle-alert", "circle-check", "circle-x",
    "clipboard", "clipboard-paste", "clock", "copy", "cpu", "download", "ellipsis-vertical", "external-link",
    "eye", "eye-off", "fast-forward", "file", "file-archive", "file-audio", "file-down", "file-plus", "file-text",
    "file-video", "folder", "folder-input", "folder-open", "folder-output", "funnel", "gauge", "globe",
    "grid-3x3", "grip-vertical", "hard-drive", "history", "hourglass", "info", "keyboard", "laptop", "layers",
    "leaf", "link", "link-2", "list", "list-filter", "list-tree", "lock", "log-out", "magnet", "maximize",
    "minimize", "minus", "monitor", "moon", "network", "pause", "picture-in-picture-2", "pin", "pin-off", "play",
    "plug", "plus", "power", "qr-code", "radio-tower", "refresh-cw", "rewind", "rotate-cw", "router", "rss",
    "scale", "scan-line", "search", "server", "settings", "share-2", "shield", "shield-check", "skip-back",
    "skip-forward", "sliders-horizontal", "smartphone", "square", "square-check", "tag", "tags", "timer",
    "trash-2", "triangle-alert", "upload", "users", "volume-2", "volume-x", "wifi", "wifi-off", "x", "zap",
]

NUM = re.compile(r"[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?")


def f(v: float) -> str:
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def element_to_path(el) -> str | None:
    tag = el.tag.split("}")[-1]
    a = el.attrib
    num = lambda k, d=0.0: float(a.get(k, d))
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num("cx"), num("cy"), num("r")
        return f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0"
    if tag == "ellipse":
        cx, cy, rx, ry = num("cx"), num("cy"), num("rx"), num("ry")
        return f"M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0"
    if tag == "rect":
        x, y, w, h = num("x"), num("y"), num("width"), num("height")
        rx = num("rx", a.get("ry", 0))
        ry = num("ry", a.get("rx", 0))
        if rx <= 0 and ry <= 0:
            return f"M{f(x)} {f(y)}H{f(x + w)}V{f(y + h)}H{f(x)}Z"
        return (
            f"M{f(x + rx)} {f(y)}H{f(x + w - rx)}A{f(rx)} {f(ry)} 0 0 1 {f(x + w)} {f(y + ry)}"
            f"V{f(y + h - ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x + w - rx)} {f(y + h)}"
            f"H{f(x + rx)}A{f(rx)} {f(ry)} 0 0 1 {f(x)} {f(y + h - ry)}"
            f"V{f(y + ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x + rx)} {f(y)}Z"
        )
    if tag == "line":
        return f"M{f(num('x1'))} {f(num('y1'))}L{f(num('x2'))} {f(num('y2'))}"
    if tag in ("polyline", "polygon"):
        pts = [float(n) for n in NUM.findall(a["points"])]
        pairs = list(zip(pts[0::2], pts[1::2]))
        d = "M" + " L".join(f"{f(px)} {f(py)}" for px, py in pairs)
        return d + ("Z" if tag == "polygon" else "")
    return None


def kotlin_name(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def main(icon_dir: Path, out: Path, version: str) -> None:
    lines = [
        f"// Generated by tools/generate_icons.py from lucide-static {version} (ISC license). Do not edit by hand.",
        "package com.graphite.torrent.ui.designsystem.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** Line icons (Lucide), 24dp grid, 1.5dp stroke. Tint them with Icon(tint = ...). */",
        "object GraphiteIcons {",
    ]
    for name in ICONS:
        svg = icon_dir / f"{name}.svg"
        root = ET.parse(svg).getroot()
        paths = [p for p in (element_to_path(el) for el in root.iter()) if p]
        args = ", ".join('"' + p.replace('"', '\\"') + '"' for p in paths)
        kn = kotlin_name(name)
        lines.append(f'    val {kn}: ImageVector by lazy {{ icon("{kn}", {args}) }}')
    lines += [
        "}",
        "",
        "private fun icon(name: String, vararg paths: String): ImageVector =",
        "    ImageVector.Builder(",
        "        name = name,",
        "        defaultWidth = 24.dp,",
        "        defaultHeight = 24.dp,",
        "        viewportWidth = 24f,",
        "        viewportHeight = 24f,",
        "    ).apply {",
        "        for (d in paths) {",
        "            addPath(",
        "                pathData = addPathNodes(d),",
        "                fill = null,",
        "                stroke = SolidColor(Color.Black),",
        "                strokeLineWidth = 1.5f,",
        "                strokeLineCap = StrokeCap.Round,",
        "                strokeLineJoin = StrokeJoin.Round,",
        "            )",
        "        }",
        "    }.build()",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(ICONS)} icons to {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3] if len(sys.argv) > 3 else "1.80.0")
